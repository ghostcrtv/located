// Runs after `vite build`: writes docs/sw.js, the offline cache list.
// Its VERSION changes whenever any file changes, which tells the iPad to update.
import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'

const OUT = 'docs'
const walk = (dir) => readdirSync(dir).flatMap((f) => {
  const p = join(dir, f)
  return statSync(p).isDirectory() ? walk(p) : [p]
})
// Everything except the optional street-imagery library (only fetched when a Mapillary key is set).
const files = walk(OUT)
  .map((p) => relative(OUT, p).split('\\').join('/'))
  .filter((f) => f !== 'sw.js' && !/mapillary/i.test(f) && !f.endsWith('.map'))
  .sort()
const hash = createHash('sha256')
for (const f of files) hash.update(f).update(readFileSync(join(OUT, f)))
const VERSION = hash.digest('hex').slice(0, 12)

const sw = `// GENERATED by tools/build-sw.mjs — makes LOCATED. work offline.
const VERSION = ${JSON.stringify(VERSION)};
const CACHE = "located-" + VERSION;
const FILES = ${JSON.stringify(['./', ...files.filter((f) => f !== 'index.html'), 'index.html'])};

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith("located-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener("fetch", (e) => {
  if (e.request.method !== "GET") return;
  const url = new URL(e.request.url);
  if (url.origin !== location.origin) return; // map tiles & street imagery: straight to the network
  e.respondWith(
    caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request).then((res) => {
      if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(e.request, copy)); }
      return res;
    }).catch(() => caches.match("./")))
  );
});
`
writeFileSync(join(OUT, 'sw.js'), sw)
console.log(`sw.js: ${files.length} files cached offline, version ${VERSION}`)
